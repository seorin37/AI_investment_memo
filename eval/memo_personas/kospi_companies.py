# 언급 검사: 긴 이름부터 찾아 'LG에너지솔루션'을 'LG'로, '한화오션'을 '한화'로 잘못 세지 않는다
_ALIAS_PAIRS = sorted({(a.lower(), c) for c in COMPANY_LIST for a in [c] + ALIASES.get(c, [])}
                      | {(a.lower(), c) for c, al in ORIGINAL_FOUR.items() for a in al},
                      key=lambda x: len(x[0]), reverse=True)


def mentions(text: str) -> list[str]:
    s, found = text.lower(), []
    for alias, comp in _ALIAS_PAIRS:
        pat = (r"(?<![a-z0-9&])" + re.escape(alias) + r"(?![a-z0-9&])") if alias.isascii() else re.escape(alias)
        for m in list(re.finditer(pat, s)):
            if "\0" in s[m.start():m.end()]:
                continue
            s = s[:m.start()] + "\0" * (m.end() - m.start()) + s[m.end():]
            if comp not in found:
                found.append(comp)
    return found


def call_names(company: str) -> list[str]:
    return [company] + ALIASES.get(company, [])


def protected_words() -> set[str]:
    """오타를 넣지 않을 단어(모든 기업 이름·별명)."""
    return {a for a, _ in _ALIAS_PAIRS}
